"""Walk the help tree of c4-cli and c4-pkm and write it as Markdown.

Usage: python -I dump_cli_help.py <output.md>
"""
import re
import subprocess
import sys

C4_DIR = r"C:\Program Files\CODESYS-4"
TOOLS = ["c4-cli", "c4-pkm"]
# Commands that start a UI or server instead of printing help-and-exit are only asked for --help.
COMMAND_LINE = re.compile(r"^    ([a-z][a-z0-9-]*)(?: <[^>]+>)*\s{2,}")


def run_help(tool, path):
    args = [rf"{C4_DIR}\{tool}.exe", *path, "--help"]
    result = subprocess.run(args, capture_output=True, text=True, encoding="utf-8", stdin=subprocess.DEVNULL,
                            errors="replace", timeout=60)
    return (result.stdout + result.stderr).rstrip()


def list_subcommands(help_text):
    names, in_commands = [], False
    for line in help_text.splitlines():
        if line.startswith("COMMANDS:"):
            in_commands = True
            continue
        if in_commands:
            if line and not line.startswith(" "):
                break
            match = COMMAND_LINE.match(line)
            if match:
                names.append(match.group(1))
    return names


def walk(tool, path, out):
    text = run_help(tool, path)
    heading = "#" * min(2 + len(path), 6)
    out.append(f"{heading} `{tool} {' '.join(path)}`".replace("  `", "`").rstrip() + "\n")
    out.append("```text\n" + text + "\n```\n")
    for name in list_subcommands(text):
        if name in ("help",):
            continue
        walk(tool, path + [name], out)


def main():
    out = ["# CODESYS 4 CLI reference\n",
           "Generated by `examples/codesys4/dump_cli_help.py` from the installed tools.\n"]
    for tool in TOOLS:
        version = subprocess.run([rf"{C4_DIR}\{tool}.exe", "version", "--verbose"],
                                 capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=60).stdout.strip()
        out.append(f"## {tool}\n")
        out.append("```text\n" + version + "\n```\n")
        walk(tool, [], out)
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
