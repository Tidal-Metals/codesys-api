"""Generate st/bcnf_style/BcnfStringPublicationCopy.st from a text dump of the BCNF project.

The body is FB_InterlockMatrix.StringPublication verbatim; the tags it reads are declared with
their BCNF types and given non-zero values, so formatting costs what it costs on site.

Usage: python examples/mqtt_large_payload/make_bcnf_copy.py <dump.txt>
The dump is the "===== <object path> [decl|impl] =====" text that a scriptengine export of every
textual object's declaration and implementation produces (kept locally, not in this repo).
"""
import json
import re
import sys
from pathlib import Path

DUMP = Path(sys.argv[1])
OUT = Path(__file__).resolve().parent / "st" / "bcnf_style" / "BcnfStringPublicationCopy.st"
DECL_RE = re.compile(r"^\s*([A-Za-z_]\w*)\s*:\s*([A-Za-z_][\w()]*)\s*(?::=\s*[^;]+)?;")


def section(text, header):
    start = text.index("===== %s =====" % header)
    start = text.index("\n", start) + 1
    end = text.find("\n===== ", start)
    return text[start:end]


source = DUMP.read_text(encoding="utf-8")
body = section(source, "P2CDS622/Plc Logic/Application/FB_InterlockMatrix/StringPublication [impl]").strip("\n")
declarations = section(source, "P2CDS622/Plc Logic/Application/FB_InterlockMatrix [decl]")
types = {}
for line in declarations.splitlines():
    match = DECL_RE.match(line)
    if match:
        types.setdefault(match.group(1), match.group(2))

used = []
for name in re.findall(r"\b[A-Za-z_]\w*\b", re.sub(r"//.*|'[^']*'", "", body)):
    if name in types and name not in used:
        used.append(name)

lines = []
real_index = bool_index = 0
for name in used:
    var_type = types[name]
    if var_type == "REAL":
        real_index += 1
        init = " := %.2f" % (3.17 + real_index * 13.71)   # varied, non-zero, two decimals
    elif var_type == "BOOL":
        bool_index += 1
        init = " := TRUE" if bool_index % 3 == 0 else ""
    elif var_type in ("DINT", "INT", "UDINT"):
        init = " := 18234"
    else:
        init = ""
    lines.append("\t%s : %s%s;" % (name, var_type, init))

lines += [
    "\t// BuildTagValue action: the same values as one tag:value line each",
    "\tTagValuePayload : STRING(4000);",
    "\tTagValueUsed : UDINT;",
    "\tIsTagValueBuildOk : BOOL;",
]

header = """PROGRAM BcnfStringPublicationCopy
// BCNF's FB_InterlockMatrix.StringPublication, copied verbatim from PLC_BCNF_4_16_26.project, with the
// tags it reads declared using their BCNF types and non-zero values. Generated by
// make_bcnf_copy.py. PLC_PRG calls it every scan when IsBcnfEveryScanEnabled is TRUE,
// to measure what rebuilding BCNF's payload strings every scan costs. Its BuildTagValue action
// builds the same values in the bridge's tag:value line format instead.
VAR
%s
END_VAR
// ---- implementation ----
""" % "\n".join(lines)
OUT.write_text(header + body + "\n", encoding="utf-8")
print(OUT, "vars:", len(used), "REAL:", real_index, "BOOL:", bool_index, "body lines:", len(body.splitlines()))
missing = sorted(set(n for n in re.findall(r"\b[A-Z][A-Z0-9_]*_[A-Z0-9_]*\b", re.sub(r"//.*|'[^']*'", "", body))) - set(types))
print("identifiers without a BCNF declaration:", missing)

# ---- BuildTagValue action: every value StringPublication appends, in order, with its exact conversion ----
VALUE_RE = re.compile(r"^BCNF_\w+ := CONCAT\(BCNF_\w+, (.+)\);\s*$")
values = []
for line in body.splitlines():
    match = VALUE_RE.match(line.strip())
    if not match or match.group(1).startswith("'"):
        continue  # separators and closing brackets
    expression = match.group(1)
    tag = next(name for name in re.findall(r"\b[A-Za-z_]\w*\b", expression) if name in types)
    values.append((tag, expression))

action = ["// Action BuildTagValue: the %d values StringPublication publishes, one \"tag:value\" line each," % len(values),
          "// the format the bridge ingests without a publish map. Generated by make_bcnf_copy.py.",
          "// ---- implementation ----",
          "TagValueUsed := 0;",
          "TagValuePayload := '';",
          "IsTagValueBuildOk := TRUE;"]
for tag, expression in values:
    action.append("IsTagValueBuildOk := IsTagValueBuildOk AND_THEN AppendTagLine(pBuffer := ADR(TagValuePayload), "
                  "Capacity := SIZEOF(TagValuePayload), Name := '%s', Value := %s, Used := TagValueUsed);" % (tag, expression))
ACTION_OUT = OUT.with_name("BcnfStringPublicationCopy.BuildTagValue.st")
ACTION_OUT.write_text("\n".join(action) + "\n", encoding="utf-8")
NAMES_OUT = OUT.with_name("BcnfTagValueNames.json")
NAMES_OUT.write_text(json.dumps([tag for tag, _ in values], indent=1) + "\n", encoding="utf-8")
print(ACTION_OUT, "lines:", len(values))
